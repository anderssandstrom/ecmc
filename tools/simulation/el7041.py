Model = EL7041


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prefix', required=True, help='simulation record prefix, e.g. c6025a-08:SIM:')
    parser.add_argument('--master', type=int, default=0)
    parser.add_argument('--slave', type=int, required=True)
    parser.add_argument('--channel', default='01')
    parser.add_argument('--rate', type=float, default=100, help='requested feedback loop rate in Hz')
    parser.add_argument('--timeout', type=float, default=1, help='CA operation timeout in seconds')
    parser.add_argument('--duration', type=float, help='stop after this many seconds; default runs until interrupted')
    parser.add_argument('--full-steps-per-second', type=float, default=2000)
    parser.add_argument('--motor-steps-per-rev', type=int, default=200)
    parser.add_argument('--encoder-counts-per-rev', type=int, default=12800)
    parser.add_argument('--counter-bits', type=int, default=16)
    parser.add_argument('--enable-delay', type=float, default=0.05)
    parser.add_argument('--initial-position-revs', type=float, help='default preserves the existing raw encoder counter')
    parser.add_argument('--lower-limit-revs', type=float)
    parser.add_argument('--upper-limit-revs', type=float)
    args = parser.parse_args(argv)
    try:
        settings = Settings(args.full_steps_per_second, args.motor_steps_per_rev,
                            args.encoder_counts_per_rev, args.counter_bits, args.enable_delay,
                            args.lower_limit_revs, args.upper_limit_revs)
        for value in (args.rate, args.timeout, args.duration if args.duration is not None else 1):
            if not math.isfinite(value) or value <= 0:
                raise ValueError('rate, timeout and duration must be finite and positive')
        if args.master < 0 or args.slave < 0 or not args.channel.isdigit() or not args.prefix:
            raise ValueError('master/slave must be nonnegative; prefix and numeric channel are required')
        if args.initial_position_revs is not None and not math.isfinite(args.initial_position_revs):
            raise ValueError('initial position must be finite')
    except ValueError as error:
        parser.error(str(error))
    try:
        from epics import PV
    except ImportError:
        parser.exit(2, 'pyepics is required: python3 -m pip install pyepics\n')
    io = EpicsIO(args.prefix, args.master, args.slave, args.channel.zfill(2), args.timeout, PV)
    def terminate(_signum, _frame):
        raise KeyboardInterrupt
    old_handler = signal.signal(signal.SIGTERM, terminate)
    try:
        io.connect()
        initial = (io.initial_position() if args.initial_position_revs is None
                   else args.initial_position_revs * settings.encoder_counts_per_rev)
        model = EL7041(settings, initial)
        print(f'EL7041 model: {io.base} channel {args.channel}; requested {args.rate:g} Hz; '
              f'{settings.full_steps_per_second:g} full steps/s, {settings.motor_steps_per_rev} steps/rev, '
              f'{settings.encoder_counts_per_rev} counts/rev', flush=True)
        run(io, model, 1 / args.rate, args.duration)
    except KeyboardInterrupt:
        print('EL7041 model stopped; enabled feedback withdrawn.', flush=True)
    except (RuntimeError, ValueError) as error:
        print('EL7041 model: ' + str(error), file=sys.stderr)
        return 1
    finally:
        io.close()
        signal.signal(signal.SIGTERM, old_handler)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
