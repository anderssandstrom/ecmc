#!/usr/bin/env python3
"""Functional EL7041 feedback model using ECMC's generated simulation field PVs."""
import argparse
from dataclasses import dataclass
import math
import signal
import sys
import time


@dataclass(frozen=True)
class Settings:
    full_steps_per_second: float = 2000.0
    motor_steps_per_rev: int = 200
    encoder_counts_per_rev: int = 12800
    counter_bits: int = 16
    enable_delay: float = 0.05
    lower_limit_revs: float = None
    upper_limit_revs: float = None

    def __post_init__(self):
        for name in ('full_steps_per_second', 'motor_steps_per_rev', 'encoder_counts_per_rev'):
            if not math.isfinite(getattr(self, name)) or getattr(self, name) <= 0:
                raise ValueError(name + ' must be finite and positive')
        if not 1 <= self.counter_bits <= 32:
            raise ValueError('counter_bits must be between 1 and 32')
        if not math.isfinite(self.enable_delay) or self.enable_delay < 0:
            raise ValueError('enable_delay must be finite and nonnegative')
        for limit in (self.lower_limit_revs, self.upper_limit_revs):
            if limit is not None and not math.isfinite(limit):
                raise ValueError('limits must be finite')
        if (self.lower_limit_revs is not None and self.upper_limit_revs is not None
                and self.lower_limit_revs >= self.upper_limit_revs):
            raise ValueError('lower limit must be below upper limit')


@dataclass(frozen=True)
class Feedback:
    drive_status: int
    encoder_status: int
    position: int


def word16(value):
    """Accept signed or unsigned representations of one native 16-bit word."""
    if value is None or not math.isfinite(value) or int(value) != value or not -32768 <= value <= 65535:
        raise ValueError('expected a finite 16-bit integer word, got ' + repr(value))
    return int(value) & 0xffff


class EL7041:
    def __init__(self, settings=Settings(), initial_counts=0):
        self.settings = settings
        if not math.isfinite(initial_counts):
            raise ValueError('initial position must be finite')
        self.position_counts = float(initial_counts)
        initial_revs = self.position_counts / settings.encoder_counts_per_rev
        if ((settings.lower_limit_revs is not None and initial_revs < settings.lower_limit_revs)
                or (settings.upper_limit_revs is not None and initial_revs > settings.upper_limit_revs)):
            raise ValueError('initial position is outside the model limits')
        self.enabled = False
        self.fault = False
        self.enable_seconds = 0.0
        self.torque_reduced = False

    def trip(self):
        self.fault = True
        self.torque_reduced = False
        self.enabled = False
        self.enable_seconds = 0.0

    def feedback(self):
        s = self.settings
        revolutions = self.position_counts / s.encoder_counts_per_rev
        low = s.lower_limit_revs is not None and revolutions <= s.lower_limit_revs
        high = s.upper_limit_revs is not None and revolutions >= s.upper_limit_revs
        # Existing EL70xx template: B0 ready, B1 enabled, B3 fault, B6 reduced torque.
        # BB/BC are modelled as normally-closed low/high limit inputs.
        status = (int(not self.fault) | (int(self.enabled) << 1) | (int(self.fault) << 3)
                  | (int(self.torque_reduced) << 6) | (int(not low) << 11) | (int(not high) << 12))
        # No encoder warning/error/latch event is generated by this simple model.
        counter = math.floor(self.position_counts) % (1 << s.counter_bits)
        return Feedback(status, 0, counter)

    def step(self, control, velocity, seconds):
        control, velocity = word16(control), word16(velocity)
        if not math.isfinite(seconds) or seconds < 0:
            raise ValueError('elapsed seconds must be finite and nonnegative')
        if control & 2:
            self.fault = False
        self.torque_reduced = bool(control & 4) and not self.fault
        moving_seconds = 0.0
        if control & 1 and not self.fault:
            self.enable_seconds += seconds
            self.enabled = self.enable_seconds >= self.settings.enable_delay
            moving_seconds = min(seconds, max(0.0, self.enable_seconds - self.settings.enable_delay))
        else:
            self.enabled = False
            self.enable_seconds = 0.0
        signed_velocity = velocity - 65536 if velocity & 0x8000 else velocity
        s = self.settings
        counts_per_second = (signed_velocity / 32768.0 * s.full_steps_per_second
                             * s.encoder_counts_per_rev / s.motor_steps_per_rev)
        position = self.position_counts + counts_per_second * moving_seconds
        if s.lower_limit_revs is not None:
            position = max(position, s.lower_limit_revs * s.encoder_counts_per_rev)
        if s.upper_limit_revs is not None:
            position = min(position, s.upper_limit_revs * s.encoder_counts_per_rev)
        self.position_counts = position
        return self.feedback()


class EpicsIO:
    """Only the generated I/O fields are accessed; no axis PVs or IOC commands."""
    def __init__(self, prefix, master, slave, channel, timeout, pv_factory):
        self.base = f'{prefix}ec{master}:s{slave}:'
        self.timeout = timeout
        fields = {'control': 'driveControl', 'velocity': 'velocitySetpoint',
                  'status': 'driveStatus', 'encoder': 'encoderStatus', 'position': 'positionActual'}
        self.pvs = {key: pv_factory(self.base + name + channel, auto_monitor=False)
                    for key, name in fields.items()}
        self.pvs['initial'] = pv_factory(self.base + 'positionActual' + channel + '-RB', auto_monitor=False)
        self.types = {key: pv_factory(pv.pvname + '.RTYP', auto_monitor=False)
                      for key, pv in self.pvs.items()}

    def connect(self):
        # Check directions through record types before writing any feedback.
        expected = {'control': 'mbbiDirect', 'velocity': 'longin', 'status': 'mbboDirect',
                    'encoder': 'mbboDirect', 'position': 'mbboDirect', 'initial': 'mbbiDirect'}
        for pv in list(self.pvs.values()) + list(self.types.values()):
            if not pv.wait_for_connection(timeout=self.timeout):
                raise RuntimeError('cannot connect to ' + pv.pvname)
        for key, pv in self.types.items():
            actual = pv.get(as_string=True, use_monitor=False, timeout=self.timeout)
            if actual != expected[key]:
                raise RuntimeError(f'{pv.pvname}: expected {expected[key]}, got {actual!r}')
        for key in ('control', 'velocity', 'initial'):
            if not self.pvs[key].read_access:
                raise RuntimeError('no read access to ' + self.pvs[key].pvname)
        for key in ('status', 'encoder', 'position'):
            if not self.pvs[key].write_access:
                raise RuntimeError('no write access to ' + self.pvs[key].pvname)

    def read(self):
        return tuple(self.pvs[key].get(use_monitor=False, timeout=self.timeout)
                     for key in ('control', 'velocity'))

    def initial_position(self):
        value = self.pvs['initial'].get(use_monitor=False, timeout=self.timeout)
        if value is None or not math.isfinite(value) or value != int(value):
            raise RuntimeError('cannot read initial encoder counter')
        return int(value)

    def publish(self, feedback):
        # Feedback enabled is published last, after encoder position/status.
        for key, value in (('position', feedback.position), ('encoder', feedback.encoder_status),
                           ('status', feedback.drive_status)):
            pv = self.pvs[key]
            if not pv.connected or pv.put(value, wait=True, timeout=self.timeout) != 1:
                raise RuntimeError('feedback write failed: ' + pv.pvname)

    def withdraw(self, feedback):
        # Best effort on shutdown/disconnect: remove enabled feedback promptly.
        pv = self.pvs['status']
        if pv.connected:
            try:
                pv.put(feedback.drive_status, wait=True, timeout=min(self.timeout, 0.25))
            except Exception:
                pass

    def close(self):
        for pv in list(self.pvs.values()) + list(self.types.values()):
            pv.disconnect()


def run(io, model, period, duration=None, clock=time.monotonic, sleep=time.sleep, stop=None):
    max_gap = max(0.25, period * 5)
    try:
        if stop is not None and stop.is_set():
            return
        io.publish(model.feedback())
        started = previous = clock()
        deadline = started
        while ((duration is None or clock() - started < duration)
               and (stop is None or not stop.is_set())):
            deadline += period
            sleep(max(0.0, deadline - clock()))
            if stop is not None and stop.is_set():
                break
            control, velocity = io.read()
            now = clock()
            elapsed = now - previous
            if elapsed > max_gap:
                raise RuntimeError(f'feedback loop stalled for {elapsed:.3f}s; stopping model')
            io.publish(model.step(control, velocity, elapsed))
            previous = now
            if deadline < now:
                deadline = now
    finally:
        model.trip()
        io.withdraw(model.feedback())


